#!/usr/bin/env python3
"""Turn the results.tsv written by audit.sh into a standalone HTML report.

Usage: python3 report_html.py results.tsv -o report.html
Uses only the Python standard library.
"""

from __future__ import annotations

import argparse
import html
import sys

COLOURS = {"PASS": "#1a7f37", "WARN": "#b26b00", "FAIL": "#c62828", "INFO": "#0b6bcb"}


def parse_tsv(path: str) -> tuple[dict, list[dict]]:
    meta: dict[str, str] = {}
    rows: list[dict] = []
    header: list[str] | None = None
    with open(path, encoding="utf-8") as fh:
        for raw in fh:
            line = raw.rstrip("\n")
            if not line:
                continue
            if line.startswith("#"):
                key, _, value = line[1:].partition("\t")
                meta[key] = value
            elif header is None:
                header = line.split("\t")
            else:
                values = line.split("\t")
                values += [""] * (len(header) - len(values))
                rows.append(dict(zip(header, values)))
    return meta, rows


def render(meta: dict, rows: list[dict]) -> str:
    e = html.escape
    counts = {s: sum(1 for r in rows if r["status"] == s) for s in COLOURS}
    score = int(meta.get("score", "0") or 0)
    bar_colour = COLOURS["PASS"] if score >= 75 else COLOURS["WARN"] if score >= 50 else COLOURS["FAIL"]

    def badge(status: str) -> str:
        return f'<span class="badge" style="background:{COLOURS.get(status, "#555")}">{e(status)}</span>'

    result_rows = "\n".join(
        f"<tr><td>{badge(r['status'])}</td><td>{e(r['id'])}</td><td>{e(r['cis'])}</td>"
        f"<td>{e(r['title'])}</td><td>{e(r['detail'])}</td></tr>"
        for r in rows)
    fixes = [r for r in rows if r["status"] in ("FAIL", "WARN")]
    fixes.sort(key=lambda r: r["status"] != "FAIL")  # FAIL first
    fix_items = "\n".join(
        f"<li>{badge(r['status'])} <strong>{e(r['title'])}</strong> "
        f"<small>({e(r['id'])}, CIS {e(r['cis'])})</small><br>{e(r['remediation'])}</li>"
        for r in fixes) or "<li>Nothing to fix. Well done!</li>"

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Linux Security Audit - {e(meta.get('host', ''))}</title>
<style>
  body {{ font-family: system-ui, -apple-system, Segoe UI, Roboto, sans-serif; margin: 2rem auto; max-width: 1000px; color: #222; padding: 0 1rem; }}
  h1 {{ margin-bottom: .2rem; }}
  .meta {{ color: #555; margin-bottom: 1.5rem; }}
  .cards {{ display: flex; gap: 1rem; flex-wrap: wrap; margin: 1rem 0 2rem; }}
  .card {{ border: 1px solid #ddd; border-radius: 8px; padding: .8rem 1.2rem; min-width: 110px; }}
  .card .n {{ font-size: 1.8rem; font-weight: 700; }}
  .bar {{ background: #eee; border-radius: 6px; height: 14px; overflow: hidden; }}
  .bar div {{ height: 100%; background: {bar_colour}; width: {score}%; }}
  table {{ border-collapse: collapse; width: 100%; font-size: .92rem; }}
  th, td {{ border-bottom: 1px solid #e5e5e5; padding: .5rem; text-align: left; vertical-align: top; }}
  th {{ background: #f6f8fa; }}
  .badge {{ color: #fff; border-radius: 4px; padding: 1px 7px; font-size: .78rem; font-weight: 700; }}
  li {{ margin-bottom: .8rem; }}
  footer {{ margin-top: 2rem; color: #777; font-size: .85rem; }}
</style>
</head>
<body>
<h1>Linux Security Audit</h1>
<div class="meta">Host <code>{e(meta.get('host', '?'))}</code> &middot; {e(meta.get('os', '?'))}
 (kernel {e(meta.get('kernel', '?'))}) &middot; {e(meta.get('date', ''))} &middot; mode: {e(meta.get('mode', ''))}</div>

<h2>Score: {score} / 100 &mdash; grade {e(meta.get('grade', ''))}</h2>
<div class="bar"><div></div></div>
<div class="cards">
  <div class="card"><div class="n" style="color:{COLOURS['PASS']}">{counts['PASS']}</div>PASS</div>
  <div class="card"><div class="n" style="color:{COLOURS['WARN']}">{counts['WARN']}</div>WARN</div>
  <div class="card"><div class="n" style="color:{COLOURS['FAIL']}">{counts['FAIL']}</div>FAIL</div>
  <div class="card"><div class="n" style="color:{COLOURS['INFO']}">{counts['INFO']}</div>INFO</div>
</div>

<h2>Results</h2>
<table>
<tr><th>Status</th><th>ID</th><th>CIS</th><th>Check</th><th>Detail</th></tr>
{result_rows}
</table>

<h2>Remediation steps</h2>
<ol>
{fix_items}
</ol>
<footer>Generated by linux-security-audit. Read-only: no changes were made.
CIS numbers refer loosely to the CIS Ubuntu Linux Benchmark and are a guide only.</footer>
</body>
</html>
"""


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Build an HTML report from audit.sh results.tsv")
    ap.add_argument("tsv")
    ap.add_argument("-o", "--output", default="report.html")
    args = ap.parse_args(argv)
    meta, rows = parse_tsv(args.tsv)
    if not rows:
        print("No results found in", args.tsv, file=sys.stderr)
        return 1
    with open(args.output, "w", encoding="utf-8") as fh:
        fh.write(render(meta, rows))
    return 0


if __name__ == "__main__":
    sys.exit(main())
